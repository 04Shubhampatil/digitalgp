/** Normalise English text for lookup: drop zero-width characters and stray spaces before full stops. */
const norm = (s: string) => s.replace(/[\u200b\u200c\u200d\ufeff]/g, "").replace(/\s+\./g, ".").replace(/[ \t]+/g, " ").trim();

const TABLE = new Map(Object.entries(MR).map(([en, mr]) => [norm(en), mr]));

/**
 * Marathi text for a known English phrase, or null. Multi-paragraph English (paragraphs separated by
 * blank lines) is translated paragraph by paragraph, and only when every paragraph is known.
 */
export function marathiFor(en: string | null | undefined): string | null {
  if (!en) return null;
  const whole = TABLE.get(norm(en));
  if (whole) return whole;
  const parts = en.split(/\n{2,}/).map((p) => p.trim()).filter(Boolean);
  if (parts.length < 2) return null;
  const out = parts.map((p) => TABLE.get(norm(p)));
  return out.every(Boolean) ? out.join("\n\n") : null;
}
